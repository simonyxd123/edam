--
-- sys_user 补一列：账号锁定**到期时间**。
--
-- 为什么需要（2026-11-14 代码审计第五轮）：
--   「连续 5 次密码错误 → 锁定 30 分钟」这条防护此前**只会锁、不会解**：
--     - LoginAttemptService.recordFailure 达到阈值就把 status 置成 3（locked）；
--     - sys_user 表里**没有任何"锁定到什么时候"的字段**（本迁移之前）；
--     - 全仓库也没有任何定时任务或逻辑把 status 从 3 改回 1。
--   ⇒ 一次误输 5 次密码 = 该账号**永久**锁死，只能由管理员逐个手工改库恢复。
--
--   而对外的说法一直是"锁定 30 分钟"（AccountLockedException 里还把
--   1800 秒当作"剩余秒数"告诉客户端）—— 那是个**假承诺**：
--   等 30 分钟并不会自动解锁。
--
--   更糟的是它可以被**主动利用**：攻击者只要知道工号（工号通常可枚举，
--   如 E0001/E0002…），连着输错 5 次就能把同事的账号永久锁死 ——
--   不需要知道密码，而且被锁的人三条登录路径（密码 / WebAuthn / SSO）
--   全部进不去（assertLoginAllowed 是三者的共同前置）。
--   逐个工号重复一遍 = 全员锁死。
--
-- 本迁移加一列 locked_until，把"锁定"从**状态**变成**有时间窗的状态**：
--   - 自动锁定（连续失败触发）：写入 locked_until = now + 30 分钟
--     ⇒ 到期自动解锁并清零失败计数；
--   - 管理员手动锁定（UserController 把 status 置 3）：locked_until 保持 NULL
--     ⇒ 语义是"管理员锁定，不自动解锁"，必须人工恢复。
--
-- 迁移只增不改 —— 不动已应用的迁移，加新列走新文件。
-- ============================================================================

ALTER TABLE sys_user
    ADD COLUMN locked_until DATETIME(3) NULL
        COMMENT '锁定到期时间（NULL = 管理员手动锁定，不自动解锁）' AFTER failed_login_count;
